"""models.yaml -> llama-swap.yaml, litellm.yaml, models.ini, downloads.json, ports.env.

llama-swap: one entry per GPU container. The llama-server entry runs in router mode with the
presets of models.ini; every preset name is an alias of that one entry, so the request's model
name reaches llama-server unchanged and switching presets never restarts the container. Each
entry's cmd is `dwyt-airouter container run <entry>`, which keeps running while the container runs.

LiteLLM: local names -> llama-swap; cloud names -> the provider with the key from the env;
stable names (auto, osszefoglalo ...) -> a target with optional thinking switch and fallbacks.
Without LiteLLM, stable names that point to a local model become presets of their own.
"""
from __future__ import annotations

import json
import os
import shlex
from pathlib import Path
from typing import Any

import yaml

from .config import DIARIZATION_REPO, WHISPER_REPOS, Config, LocalModel

HEADER = "# Generated by `dwyt-airouter generate` from {src}. Do not edit; edit models.yaml and generate again.\n"
MODELS_IN_CONTAINER = "/models/gguf"


def _model_info(max_in: int | None, max_out: int | None, vision: bool | None) -> dict[str, Any]:
    info: dict[str, Any] = {}
    if max_in:
        info["max_input_tokens"] = max_in
    if max_out:
        info["max_output_tokens"] = max_out
    if vision is not None:
        info["supports_vision"] = vision
    return info


def _ini_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def container_path(hf_file: str) -> str:
    """owner/repo/file.gguf -> where dwyt-gpu download puts it (downloads.json version 2): each repo has its
    own folder, because repos often hold files of the same name (mmproj-F16.gguf)."""
    return f"{MODELS_IN_CONTAINER}/{hf_file}"


def _preset(name: str, model: LocalModel, thinking: bool | None = None) -> list[str]:
    lines = [f"[{name}]", f"model = {container_path(model.file)}"]
    if model.mmproj:
        lines.append(f"mmproj = {container_path(model.mmproj)}")
    args = dict(model.args)
    if thinking is not None:  # keep the model's own template switches (preserve_thinking ...)
        kwargs = json.loads(str(args.get("chat-template-kwargs") or "{}"))
        args["chat-template-kwargs"] = json.dumps({**kwargs, "enable_thinking": thinking})
    for key, value in args.items():
        lines.append(f"{key} = {_ini_value(value)}")
    return lines + [""]


def preset_names(cfg: Config) -> list[str]:
    """Names llama-server answers to: the local models, plus without LiteLLM the stable names."""
    names = [m.name for m in cfg.local_models]
    if not cfg.litellm:
        names += [n.name for n in cfg.names]
    return names


def models_ini(cfg: Config) -> str:
    lines = [HEADER.format(src=cfg.path).replace("# ", "; ", 1).rstrip("\n"), "version = 1", ""]
    if cfg.llama_args:
        lines += ["[*]"] + [f"{k} = {_ini_value(v)}" for k, v in cfg.llama_args.items()] + [""]
    local = {m.name: m for m in cfg.local_models}
    for m in cfg.local_models:
        lines += _preset(m.name, m)
    if not cfg.litellm:
        for n in cfg.names:
            lines += _preset(n.name, local[n.model], n.thinking)
    return "\n".join(lines)


def _cmd(cfg: Config, action: str, entry: str) -> str:
    base = [cfg.program, "--config", str(cfg.path), "container", action, entry]
    return " ".join(shlex.quote(p) for p in base) + (" ${PID}" if action == "stop" else "")


def llama_swap(cfg: Config) -> dict[str, Any]:
    wake_s = cfg.gpu_host.wake.wait_s if cfg.gpu_host.wake else 0
    models: dict[str, Any] = {}
    for c in cfg.containers():
        entry: dict[str, Any] = {
            "name": c.title or (f"llama-server ({c.container})" if c is cfg.llama else
                                f"Whisper GPU worker ({c.container})" if c is cfg.whisper else c.container),
            "cmd": _cmd(cfg, "run", c.entry),
            "cmdStop": _cmd(cfg, "stop", c.entry),
            "proxy": f"http://{cfg.gpu_host.address}:{c.port}",
            "checkEndpoint": c.check,
            "unloadTimeout": 60,
        }
        if c is cfg.llama:
            entry["aliases"] = preset_names(cfg)
        if c.unlisted:
            entry["unlisted"] = True
        if c.ttl:
            entry["ttl"] = c.ttl
        models[c.entry] = entry
    return {"healthCheckTimeout": cfg.gpu_host.start_timeout_s + wake_s, "logLevel": "info", "models": models}


def _thinking_params(model: str, thinking: bool | None, local: bool) -> dict[str, Any]:
    if thinking is None:
        return {}
    if local:
        return {"extra_body": {"chat_template_kwargs": {"enable_thinking": thinking}}}
    if model.startswith("openrouter/"):
        return {"extra_body": {"reasoning": {"enabled": thinking}}}
    return {"reasoning_effort": "medium" if thinking else "none"}


# ---- what each name means, for the users of the runner (dwyt central's Runners page) ------------

KNOWN_NAMES = {
    "auto": "Általános használat; ha a GPU-gép nem érhető el, a felhőben válaszol",
    "osszefoglalo": "Nyilvános videók összefoglalója és fordítása",
    "osszefoglalo-helyi": "Saját felvételek összefoglalója, fordítása és kérdései; csak helyi",
    "kerdes": "Kérdések a videókról és a könyvtárról",
}
PRESET_LABELS = {"code": "kódoló beállítás", "gnrl": "általános beállítás", "general": "általános beállítás"}


def _local_label(name: str) -> str:
    """Qwen3.6-35B-A3B-Gnrl -> "Qwen3.6-35B-A3B, általános beállítás"."""
    base, _, suffix = name.rpartition("-")
    label = PRESET_LABELS.get(suffix.lower())
    return f"{base}, {label}" if base and label else name


def _cloud_label(model: str) -> tuple[str, str]:
    """openrouter/qwen/qwen3.8-flash -> ("qwen/qwen3.8-flash", "OpenRouter")."""
    provider, _, rest = model.partition("/")
    names = {"openrouter": "OpenRouter", "openai": "OpenAI", "anthropic": "Anthropic", "gemini": "Google"}
    return (rest or model), names.get(provider, provider)


def _auto_description(name: str, target_local: bool, target: str) -> str:
    if name in KNOWN_NAMES:
        return KNOWN_NAMES[name]
    if name.startswith("osszefoglalo"):
        return "Összefoglaló és fordítás, választható" + ("; csak helyi" if name.endswith("-helyi") else "")
    if name.startswith("kerdes"):
        return "Kérdések, választható" + ("; csak helyi" if name.endswith("-helyi") else "")
    if target_local:
        suffix = name.rpartition("-")[2].lower()
        return {"code": "Kódolás", "gnrl": "Általános feladatok", "general": "Általános feladatok"}.get(
            suffix, "Helyi modell")
    return "Felhős modell"


def _thinking_of(cfg: Config, model: str, thinking: bool | None) -> tuple[bool | None, int | None]:
    """(thinking on?, its token budget) as the name will actually run."""
    local = next((m for m in cfg.local_models if m.name == model), None)
    if local is not None:
        budget = local.args.get("reasoning-budget")
        budget = int(budget) if isinstance(budget, (int, float)) or str(budget).isdigit() else None
        on = thinking if thinking is not None else (True if budget else None)
        return on, (budget if on else None)
    cloud = next((m for m in cfg.cloud_models if m.name == model), None)
    return (thinking if thinking is not None else (cloud.thinking if cloud else None)), None


def describe(cfg: Config, name: str) -> dict[str, Any]:
    """The `dwyt` block of a name's model_info: what runs behind it and what happens without the GPU host."""
    local = {m.name: m for m in cfg.local_models}
    cloud = {m.name: m for m in cfg.cloud_models}
    stable = {n.name: n for n in cfg.names}
    n = stable.get(name)
    model, thinking, fallback, own = (n.model, n.thinking, n.fallback, n.description) if n else (name, None, [], "")
    if model in local:
        m = local[model]
        out: dict[str, Any] = {"where": "local", "target": m.name, "target_label": _local_label(m.name),
                               "context": m.max_input_tokens, "vision": m.vision}
        own = own or m.description
    else:
        c = cloud[model]
        label, provider = _cloud_label(c.model)
        out = {"where": "cloud", "target": c.model, "target_label": label, "provider": provider,
               "context": c.max_input_tokens}
        own = own or c.description
        thinking = thinking if thinking is not None else c.thinking
    on, budget = _thinking_of(cfg, model, thinking)
    out.update(description=own or _auto_description(name, model in local, model), thinking=on,
               thinking_budget=budget, fallback=[])
    for f in fallback:
        target = describe(cfg, f)
        out["fallback"].append({k: target.get(k) for k in ("target", "target_label", "where", "provider", "thinking")}
                               | {"name": f})
    return {k: v for k, v in out.items() if v is not None}


def litellm(cfg: Config) -> dict[str, Any]:
    api_base = f"http://127.0.0.1:{cfg.swap_port}/v1"
    entries: list[dict[str, Any]] = []
    params: dict[str, tuple[dict[str, Any], dict[str, Any], bool]] = {}
    for m in cfg.local_models:
        p = {"model": f"openai/{m.name}", "api_base": api_base, "api_key": "none",
             "timeout": 1800,          # a model swap plus a long answer
             "stream_timeout": 600}    # wait for the first token, swap included
        info = _model_info(m.max_input_tokens, m.max_output_tokens, m.vision)
        params[m.name] = (p, info, True)
        entries.append({"model_name": m.name, "model_info": info, "litellm_params": p})
    for m in cfg.cloud_models:
        p = {"model": m.model, "api_key": f"os.environ/{cfg.cloud_key_env}", "timeout": 600,
             **_thinking_params(m.model, m.thinking, local=False)}
        info = _model_info(m.max_input_tokens, m.max_output_tokens, None)
        params[m.name] = (p, info, False)
        entries.append({"model_name": m.name, **({"model_info": info} if info else {}), "litellm_params": p})
    fallbacks = []
    for n in cfg.names:
        base, info, local = params[n.model]
        p = {**base, **_thinking_params(base["model"], n.thinking, local)}
        entries.append({"model_name": n.name, **({"model_info": info} if info else {}), "litellm_params": p})
        if n.fallback:
            fallbacks.append({n.name: n.fallback})
    for e in entries:
        e["model_info"] = {**(e.get("model_info") or {}), "dwyt": describe(cfg, e["model_name"])}
    return {
        "model_list": entries,
        "router_settings": {"fallbacks": fallbacks, "num_retries": 0,  # a switched-off GPU host does not get better
                            "allowed_fails": 1, "cooldown_time": 30},
        "litellm_settings": {"drop_params": True},
        "general_settings": {"master_key": "os.environ/LITELLM_MASTER_KEY"},
    }


def downloads(cfg: Config) -> dict[str, Any]:
    files, seen = [], set()
    for m in cfg.local_models:
        for f in [m.file] + ([m.mmproj] if m.mmproj else []):
            owner, repo, path = f.split("/", 2)
            if f not in seen:
                seen.add(f)
                files.append({"repo": f"{owner}/{repo}", "path": path})
    snapshots = []
    if cfg.whisper:
        snapshots += [{"repo": WHISPER_REPOS[m]} for m in cfg.whisper_models]
        if cfg.diarization:
            snapshots.append({"repo": DIARIZATION_REPO, "gated": True})
        snapshots += [{"repo": p} for p in cfg.prefetch]
    return {"version": 2, "files": files, "snapshots": snapshots}  # 2: files under gguf/<owner>/<repo>/


class _NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


def _dump(data: dict[str, Any]) -> str:
    return yaml.dump(data, Dumper=_NoAliases, sort_keys=False, allow_unicode=True, width=10_000)


def outputs(cfg: Config) -> dict[str, str]:
    head = HEADER.format(src=cfg.path)
    out = {
        "llama-swap.yaml": head + _dump(llama_swap(cfg)),
        "models.ini": models_ini(cfg),
        "downloads.json": json.dumps(downloads(cfg), indent=2) + "\n",
        "ports.env": head + f"SWAP_LISTEN={cfg.swap_listen}:{cfg.swap_port}\n"
                            f"LITELLM_HOST={cfg.litellm_listen}\nLITELLM_PORT={cfg.litellm_port}\n",
    }
    if cfg.litellm:
        out["litellm.yaml"] = head + _dump(litellm(cfg))
    return out


def write(cfg: Config, out_dir: str | Path) -> list[Path]:
    """Write every output atomically; returns the files that changed."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in outputs(cfg).items():
        target = out / name
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        tmp = target.with_suffix(target.suffix + ".tmp")
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, target)
        changed.append(target)
    if not cfg.litellm and (out / "litellm.yaml").exists():
        (out / "litellm.yaml").unlink()
        changed.append(out / "litellm.yaml")
    return changed
